export const DEFAULT_LANGUAGE = 'es';

export function languageLabel(code: string): string {
  const found = LANGUAGES.find((l) => l.code === code);
  return found ? `${found.nativeName} (${found.name})` : code;
}

/** Nombre del idioma para usar dentro de un prompt ("Spanish", "English"...). */
export function languageNameForPrompt(code: string): string {
  if (code === 'multi') return 'the same language the other party is speaking';
  return LANGUAGES.find((l) => l.code === code)?.name ?? code;
}
